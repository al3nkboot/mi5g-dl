"""Generates the Mi5G Dl launcher icon (Android vector XML + preview PNGs).
Design: '5G' monogram above a download arrow dropping into a tray, on a dark purple gradient."""
import os, sys
RES = sys.argv[1]
OUT = sys.argv[2]
BG_TOP, BG_BOTTOM = "#2B0A63", "#05000C"
GLYPH = "#F3ECFF"
ACCENT = "#9B6BFF"
# (pathData, color, strokeWidth)
FG = [
    ("M51,30.5 H38.5 V39.5 H45.5 Q51,39.5 51,44.75 Q51,50 45.5,50 H36.5", GLYPH, 4.6),        # 5
    ("M71.5,33.5 Q69,30.5 64.5,30.5 Q57,30.5 57,40.25 Q57,50 64.5,50 Q71.5,50 71.5,44 V41.5 H65", GLYPH, 4.6),  # G
    ("M54,55 V70", ACCENT, 5.0),                    # arrow shaft
    ("M47.5,63.5 L54,70 L60.5,63.5", ACCENT, 5.0),  # arrow head
    ("M39,68 V77 H69 V68", ACCENT, 4.2),            # tray
]

def vec_paths(color_override=None, indent="    "):
    out = []
    for d, c, w in FG:
        out.append(f'''{indent}<path
{indent}    android:pathData="{d}"
{indent}    android:fillColor="#00000000"
{indent}    android:strokeColor="{color_override or c}"
{indent}    android:strokeWidth="{w}"
{indent}    android:strokeLineCap="round"
{indent}    android:strokeLineJoin="round" />''')
    return "\n".join(out)

HDR = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Mi5G Dl launcher artwork (generated by branding/make_icon.py). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
'''
files = {
 "drawable/ic_launcher_background.xml": HDR + f'''    <path android:pathData="M0,0 H108 V108 H0 Z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108"
                android:startColor="{BG_TOP}" android:endColor="{BG_BOTTOM}" />
        </aapt:attr>
    </path>
</vector>
''',
 "drawable/ic_launcher_foreground.xml": HDR + vec_paths() + "\n</vector>\n",
 "drawable/ic_launcher_monochrome.xml": HDR + vec_paths("#FFFFFFFF") + "\n</vector>\n",
 # notification small icon: white silhouette, scaled to fill 24dp
 "drawable/ic_notification.xml": HDR.replace('android:width="108dp"','android:width="24dp"').replace('android:height="108dp"','android:height="24dp"').replace('android:viewportWidth="108"','android:viewportWidth="52"').replace('android:viewportHeight="108"','android:viewportHeight="52"')
   + '    <group android:translateX="-28" android:translateY="-27.5">\n' + vec_paths("#FFFFFFFF", "        ") + "\n    </group>\n</vector>\n",
 # in-app logo / splash: rounded tile with gradient + foreground
 "drawable/mi5g_logo.xml": HDR + f'''    <path android:pathData="M24,0 H84 A24,24 0 0 1 108,24 V84 A24,24 0 0 1 84,108 H24 A24,24 0 0 1 0,84 V24 A24,24 0 0 1 24,0 Z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108"
                android:startColor="{BG_TOP}" android:endColor="{BG_BOTTOM}" />
        </aapt:attr>
    </path>
    <group android:pivotX="54" android:pivotY="54" android:scaleX="1.35" android:scaleY="1.35">
''' + vec_paths(indent="        ") + "\n    </group>\n</vector>\n",
}
for rel, txt in files.items():
    open(os.path.join(RES, rel), "w").write(txt)

# SVG preview + legacy PNGs
import cairosvg
def svg(size, mask="circle", scale=1.0):
    paths = "".join(f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>' for d,c,w in FG)
    clip = '<clipPath id="m"><circle cx="54" cy="54" r="54"/></clipPath>' if mask=="circle" else '<clipPath id="m"><rect width="108" height="108" rx="24"/></clipPath>'
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">
<defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOTTOM}"/></linearGradient>{clip}</defs>
<g clip-path="url(#m)"><rect width="108" height="108" fill="url(#g)"/><g transform="translate(54 54) scale({scale}) translate(-54 -54)">{paths}</g></g></svg>'''
os.makedirs(OUT, exist_ok=True)
cairosvg.svg2png(bytestring=svg(512).encode(), write_to=os.path.join(OUT, "icon-circle-512.png"))
cairosvg.svg2png(bytestring=svg(512, "rounded").encode(), write_to=os.path.join(OUT, "icon-squircle-512.png"))
open(os.path.join(OUT, "icon.svg"), "w").write(svg(512, "rounded"))
# legacy density PNGs (scaled up so artwork fills a legacy 48dp icon)
for dpi, px in {"mdpi":48,"hdpi":72,"xhdpi":96,"xxhdpi":144,"xxxhdpi":192}.items():
    d = os.path.join(RES, f"mipmap-{dpi}")
    for f in ("ic_launcher_foreground.png",):
        p = os.path.join(d, f)
        if os.path.exists(p): os.remove(p)
    cairosvg.svg2png(bytestring=svg(px, "circle", 1.35).encode(), write_to=os.path.join(d, "ic_launcher.png"))
print("done")
